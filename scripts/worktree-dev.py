#!/usr/bin/env python3
"""Manage one checkout's isolated, disposable Docker Compose dev environment."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import socket
import subprocess
import sys


MARKER = '# Generated by Chronolist worktree-dev v1; do not edit.'


def settings(root: Path, slot: int | None = None) -> dict[str, str]:
    identity = hashlib.sha256(os.fsencode(root.resolve())).hexdigest()[:16]
    if slot is None:
        slot = int(identity, 16) % 10000
    if not 0 <= slot <= 9999:
        raise ValueError('slot must be between 0 and 9999')
    project = 'chronolist-' + identity
    host = project + '.localhost'
    frontend = 20000 + 2 * slot
    return {
        'COMPOSE_PROJECT_NAME': project,
        'CHRONOLIST_SLOT': str(slot),
        'CHRONOLIST_BIND_ADDRESS': '127.0.0.1',
        'CHRONOLIST_FRONTEND_PORT': str(frontend),
        'CHRONOLIST_BACKEND_PORT': str(frontend + 1),
        'CHRONOLIST_FRONTEND_ORIGIN': f'http://{host}:{frontend}',
        'CHRONOLIST_API_BASE_URL': f'http://{host}:{frontend + 1}',
    }


def load_settings(root: Path) -> dict[str, str]:
    path = root / '.env'
    if path.is_symlink():
        raise ValueError('Refusing a symlink .env; use a worktree-local generated file.')
    if not path.exists():
        raise ValueError('Run init on the host before operating this environment.')
    lines = path.read_text(encoding='utf-8').splitlines()
    if not lines or lines[0] != MARKER:
        raise ValueError('Existing .env is not managed by worktree-dev; it has been left untouched.')
    try:
        pairs = [line.split('=', 1) for line in lines[1:]]
        config = dict(pairs)
        if len(pairs) != len(config):
            raise ValueError('duplicate key')
        expected = settings(root, int(config['CHRONOLIST_SLOT']))
    except (KeyError, ValueError) as error:
        raise ValueError('Invalid generated .env; restore it before operating the environment.') from error
    if config != expected:
        raise ValueError('Generated .env was edited or copied from another checkout. '
                         'Stop the original environment before removing this file and running init here.')
    return config


def initialize(root: Path, slot: int | None = None) -> dict[str, str]:
    path = root / '.env'
    if path.exists() or path.is_symlink():
        config = load_settings(root)
        if slot is not None and config != settings(root, slot):
            raise ValueError('To change slot, run down first, remove the generated .env, '
                             'then init --slot N. Existing settings were left untouched.')
        return config
    config = settings(root, slot)
    # Exclusive creation also protects an existing file if another init races us.
    with path.open('x', encoding='utf-8', newline='\n') as handle:
        handle.write(MARKER + '\n')
        handle.writelines(f'{key}={value}\n' for key, value in config.items())
    return config


def compose_command(root: Path, config: dict[str, str], args: list[str]) -> list[str]:
    return ['docker', 'compose', '--project-directory', str(root),
            '--env-file', str(root / '.env'), '-f', str(root / 'compose.yaml'),
            '-p', config['COMPOSE_PROJECT_NAME'], *args]


def compose_environment(config: dict[str, str]) -> dict[str, str]:
    env = {key: value for key, value in os.environ.items()
           if not key.upper().startswith(('COMPOSE_', 'CHRONOLIST_'))}
    env.update(config)
    return env


def running_ports(root: Path, config: dict[str, str]) -> set[int]:
    result = subprocess.run(compose_command(root, config, ['ps', '--format', 'json']),
                            cwd=root, env=compose_environment(config), check=True,
                            capture_output=True, text=True)
    raw = result.stdout.strip()
    # Compose v2 versions emit either a JSON array or one JSON object per line.
    rows = json.loads(raw) if raw.startswith('[') else [json.loads(line) for line in raw.splitlines()]
    ports = set()
    for row in rows:
        service = row.get('Service')
        if row.get('State') != 'running' or service not in ('frontend', 'backend'):
            continue
        target = 5173 if service == 'frontend' else 8080
        published = int(config[f'CHRONOLIST_{service.upper()}_PORT'])
        for publisher in row.get('Publishers') or []:
            if (publisher.get('TargetPort') == target
                    and publisher.get('PublishedPort') == published
                    and publisher.get('URL') == config['CHRONOLIST_BIND_ADDRESS']
                    and publisher.get('Protocol') == 'tcp'):
                ports.add(published)
    return ports


def check_ports(config: dict[str, str], owned: set[int]) -> None:
    for service in ('FRONTEND', 'BACKEND'):
        port = int(config[f'CHRONOLIST_{service}_PORT'])
        if port in owned:
            continue
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
            # Exclusive bind on Windows too; do not accidentally share a listener.
            if hasattr(socket, 'SO_EXCLUSIVEADDRUSE'):
                probe.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
            try:
                probe.bind(('127.0.0.1', port))
            except OSError as error:
                raise ValueError(f'Port {port} is unavailable. Run down, remove the generated .env, '
                                 'then init --slot N with another slot. No environment was stopped.') from error


def show_urls(config: dict[str, str]) -> None:
    print('Project:  ' + config['COMPOSE_PROJECT_NAME'])
    print('Frontend: ' + config['CHRONOLIST_FRONTEND_ORIGIN'])
    print('Backend:  ' + config['CHRONOLIST_API_BASE_URL'])
    print('Use these dedicated hostnames to keep browser sessions separate.')


def run_action(root: Path, action: str) -> None:
    config = load_settings(root)
    actions = {
        'up': ['up', '-d', '--build', 'backend', 'frontend'],
        'status': ['ps', '--all'],
        'logs': ['logs', '--tail', '100', 'backend', 'frontend'],
        'stop': ['stop', 'backend', 'frontend'],
        'restart': ['restart', 'backend', 'frontend'],
        'down': ['down'],
        'destroy': ['down', '--volumes'],
    }
    if action == 'up':
        check_ports(config, running_ports(root, config))
    subprocess.run(compose_command(root, config, actions[action]),
                   cwd=root, env=compose_environment(config), check=True)
    if action in ('up', 'restart', 'status'):
        show_urls(config)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='action', required=True)
    init = commands.add_parser('init', help='generate a local .env without overwriting existing settings')
    init.add_argument('--slot', type=int, help='port slot 0–9999 (default: derived from checkout path)')
    for action, help_text in {
        'up': 'build/start FE and BE, then show URLs',
        'status': 'show containers and URLs',
        'logs': 'show the last 100 FE/BE log lines',
        'stop': 'stop FE/BE (H2 data and sessions are lost)',
        'restart': 'restart FE/BE and reset H2 data and sessions',
        'down': 'remove this project containers/network, keeping cache volumes',
        'destroy': 'remove this project containers/network AND all its named volumes',
    }.items():
        commands.add_parser(action, help=help_text)
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    try:
        if args.action == 'init':
            show_urls(initialize(root, args.slot))
        else:
            run_action(root, args.action)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f'worktree-dev: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
