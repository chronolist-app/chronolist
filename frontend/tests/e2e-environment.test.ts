import assert from 'node:assert/strict';
import test from 'node:test';
import { loadE2eEnvironment, resultPath } from '../e2e/environment.ts';

const local = {
    E2E_BASE_URL: 'http://chronolist-one.localhost:20000',
    E2E_API_BASE_URL: 'http://chronolist-one.localhost:20001',
};

test('worker が引き継いだ実行 ID では同じ結果先を使い、新規実行と URL は分離する', () => {
    const runtime = {};
    const first = resultPath(local.E2E_BASE_URL, runtime);
    assert.equal(resultPath(local.E2E_BASE_URL, { ...runtime }), first);
    assert.notEqual(resultPath(local.E2E_BASE_URL, {}), first);
    assert.notEqual(resultPath('http://other.localhost:20002', runtime), first);
});

test('検証 URL は worktree の生成済み設定から読み込める', () => {
    const result = loadE2eEnvironment({}, '# Generated by Chronolist worktree-dev v1; do not edit.\nCHRONOLIST_FRONTEND_ORIGIN=http://one.localhost:20000\nCHRONOLIST_API_BASE_URL=http://one.localhost:20001\n');
    assert.equal(result.baseURL, 'http://one.localhost:20000');
    assert.equal(result.artifacts, 'failures');
});

test('実環境・パス付き URL・異なる API ホストを拒否する', () => {
    for (const url of ['https://example.com', 'http://localhost:5173', 'http://one.localhost/path', 'http://user:pass@one.localhost', 'ftp://one.localhost']) {
        assert.throws(() => loadE2eEnvironment({ ...local, E2E_BASE_URL: url }), /URL/);
    }
    assert.throws(() => loadE2eEnvironment({ ...local, E2E_API_BASE_URL: 'http://other.localhost:20001' }), /ホスト/);
    assert.throws(() => loadE2eEnvironment({}), /URL/);
    assert.throws(() => loadE2eEnvironment({}, 'CHRONOLIST_FRONTEND_ORIGIN=http://one.localhost:20000\nCHRONOLIST_API_BASE_URL=http://one.localhost:20001'), /生成済み/);
});

test('peer は両 URL と独立ホストを要求する', () => {
    assert.throws(() => loadE2eEnvironment({ ...local, E2E_PEER_BASE_URL: 'http://two.localhost:20002' }), /peer/);
    assert.throws(() => loadE2eEnvironment({ ...local, E2E_PEER_BASE_URL: local.E2E_BASE_URL, E2E_PEER_API_BASE_URL: local.E2E_API_BASE_URL }), /ホスト/);
    const result = loadE2eEnvironment({ ...local, E2E_PEER_BASE_URL: 'http://two.localhost:20002', E2E_PEER_API_BASE_URL: 'http://two.localhost:20003', E2E_ARTIFACTS: 'all' });
    assert.equal(result.peer?.baseURL, 'http://two.localhost:20002');
    assert.equal(result.artifacts, 'all');
});

test('不正な保存方針と URL の片側指定を拒否する', () => {
    assert.throws(() => loadE2eEnvironment({ ...local, E2E_ARTIFACTS: 'always' }), /E2E_ARTIFACTS/);
    assert.throws(() => loadE2eEnvironment({ E2E_BASE_URL: local.E2E_BASE_URL }, 'CHRONOLIST_API_BASE_URL=http://one.localhost:20001'), /URL/);
});
