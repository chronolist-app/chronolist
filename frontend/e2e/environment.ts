import { createHash, randomUUID } from 'node:crypto';

type Target = { baseURL: string; apiBaseURL: string };
type Environment = Record<string, string | undefined>;

/** 親プロセスの実行 ID を worker へ引き継ぎ、URL ごとに結果先を分離する。 */
export function resultPath(baseURL: string, env: Environment): string {
    const runId = env.CHRONOLIST_E2E_RUN_ID ?? `${new Date().toISOString().replace(/[:.]/g, '-')}-${randomUUID()}`;
    if (!/^[\da-fTZ-]+$/.test(runId)) throw new Error('検証結果の実行 ID が不正です。');
    env.CHRONOLIST_E2E_RUN_ID = runId;
    const targetId = createHash('sha256').update(baseURL).digest('hex').slice(0, 12);
    return `e2e-results/${targetId}/${runId}`;
}

function localOrigin(value: string | undefined): string {
    if (!value) throw new Error('検証用 URL を指定してください。worktree-dev init または E2E_BASE_URL / E2E_API_BASE_URL が必要です。');
    const url = new URL(value);
    if (!['http:', 'https:'].includes(url.protocol) || !url.hostname.endsWith('.localhost')
        || url.username || url.password || url.pathname !== '/' || url.search || url.hash) {
        throw new Error('検証用 URL は認証情報・パスのない *.localhost の HTTP(S) origin にしてください。');
    }
    return url.origin;
}

function target(base: string | undefined, api: string | undefined): Target {
    const baseURL = localOrigin(base);
    const apiBaseURL = localOrigin(api);
    if (new URL(baseURL).hostname !== new URL(apiBaseURL).hostname) {
        throw new Error('Frontend と API は同じ worktree ホストにしてください。');
    }
    return { baseURL, apiBaseURL };
}

/** 実行環境または worktree の生成済み .env からローカル専用の検証設定を読む。 */
export function loadE2eEnvironment(env: Environment, generatedEnv = '') {
    const explicit = env.E2E_BASE_URL !== undefined || env.E2E_API_BASE_URL !== undefined;
    if (!explicit && !generatedEnv.startsWith('# Generated by Chronolist worktree-dev v1; do not edit.\n')
        && !generatedEnv.startsWith('# Generated by Chronolist worktree-dev v1; do not edit.\r\n')) {
        throw new Error('検証用 URL には worktree-dev 生成済み .env または明示した両 E2E URL が必要です。');
    }
    const generated = Object.fromEntries(generatedEnv.split(/\r?\n/)
        .filter(line => line.startsWith('CHRONOLIST_'))
        .map(line => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1)]));
    const primary = target(explicit ? env.E2E_BASE_URL : generated.CHRONOLIST_FRONTEND_ORIGIN,
        explicit ? env.E2E_API_BASE_URL : generated.CHRONOLIST_API_BASE_URL);
    let peer: Target | undefined;
    if (env.E2E_PEER_BASE_URL !== undefined || env.E2E_PEER_API_BASE_URL !== undefined) {
        if (!env.E2E_PEER_BASE_URL || !env.E2E_PEER_API_BASE_URL) throw new Error('peer は両方の URL を指定してください。');
        peer = target(env.E2E_PEER_BASE_URL, env.E2E_PEER_API_BASE_URL);
        if (new URL(peer.baseURL).hostname === new URL(primary.baseURL).hostname) {
            throw new Error('peer は別 worktree の独立ホストを指定してください。');
        }
    }
    const artifacts = env.E2E_ARTIFACTS ?? 'failures';
    if (artifacts !== 'failures' && artifacts !== 'all') throw new Error('E2E_ARTIFACTS は failures または all を指定してください。');
    return { ...primary, peer, artifacts };
}
